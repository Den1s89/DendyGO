#define DENDY_TRACE_RAM_A      0x0770
#define DENDY_TRACE_RAM_B      0x06FC

// ==================== 0.3. СКОРОСТЬ ГОРЯЧИХ ФАЙЛОВ ЯДРА =====================
// 1 — файлы ядра (NesCpu/NesPpu/NesApu/NesCore/NesMapper) компилируются с
//     -O3 через #pragma GCC optimize("O3") в DendyFast.h. Нужно потому, что
//     Arduino IDE при Debug Level = Debug собирает всё с -Og, а интерпретатор
//     6502 с шиной на -Og еле-еле даёт ~30 кадров/с вместо 60.
//     На логику это не влияет (никаких «быстрых математик»), только на код.
// 0 — доверить оптимизацию сборке (проверить, что Debug Level = None).
#define DENDY_CORE_O3          1

// ==================== 0.4. ПРОФИЛЬ ЭМУЛЯЦИИ (по частям) ======================
// 1 — в строке [GAME] печатать, на что уходит время кадра:
//     cpu  — выполнение инструкций 6502;
//     ppu  — продвижение PPU (вместе с отрисовкой строк);
//     render — сколько из ppu ушло именно на отрисовку строк (фон + спрайты);
//     apu  — микширование звука.
// Нужно, чтобы не угадывать, что тормозит: если, например, render ~2 мс, а cpu
// ~20 мс, то оптимизировать надо интерпретатор 6502, а не рендерер.
// Цена: ~4 чтения счётчика тактов на инструкцию 6502 (~1..2 % времени кадра).
// 0 — не измерять (и не печатать) — максимальная скорость.
// ВРЕМЕННО 1: без строки `profil` не видно, куда ушли ~3 мс на кадр (в README
// замер этой же платы: `emu 16,2 ms/kadr` при 60,0 кадрах/с, сейчас `emu 19,4`
// при 49,4). Цена профиля — 1..2 % времени кадра, для игры верните 0.
#define DENDY_EMU_PROFILE      0

// ==================== 0.5. КЭШ ОКОН БАНКОВ PRG/CHR (SRAM) ===================
// 1 — активные окна банков картриджа (4 x 8 КБ PRG + 8 x 1 КБ CHR) копируются
//     во ВНУТРЕННЮЮ SRAM (NesMapper::prgWindow()/chrWindow()).
//     Зачем: PRG и CHR лежат в PSRAM, а это самые горячие обращения эмулятора —
//     PRG читается 2..4 раза на каждую инструкцию 6502, CHR — на каждый тайл фона
//     и спрайта (десятки тысяч раз за кадр). Чтение из PSRAM идёт через кэш 32 КБ,
//     мимо которого всё время промахиваются и интерпретатор, и рендерер (профиль
//     показывает ~60 тактов на пиксель!). Внутренняя SRAM читается за 1..2 такта и
//     её не вытесняет кадровый буфер. Копия банка делается только при СМЕНЕ банка
//     (десятки раз за кадр) и стоит ~30..60 мкс. Занимает 40 КБ внутренней памяти.
// 0 — читать ром прямо из PSRAM (как раньше: меньше памяти, но медленнее).
#define DENDY_CART_IRAM        1

// ==================== 0.6. ГРАНУЛЯРНОСТЬ APU (такты CPU) =====================
// APU продвигается не на каждую инструкцию 6502 (это ~10 000 вызовов за кадр и
// изрядная доля времени), а когда накопится столько тактов CPU.
// ВАЖНО ПРО ЗВУК: «на результат это не влияет» — верно ТОЛЬКО для таймеров
// каналов и frame counter (они считаются точно, отсюда правильная высота тона и
// темп). Но к ГЕНЕРАЦИИ СЭМПЛОВ это не относится: сэмпл снимается в конкретный
// момент времени, и если продвинуть каналы всей порцией (128 тактов ≈ 71 мкс),
// то несколько сэмплов подряд получат одно и то же состояние каналов — звук
// обновлялся бы с частотой ~14 кГц вместо 44,1 кГц, и всё быстрое (шум, DMC,
// высокие ноты) заворачивалось бы в слышимый диапазон («песок»). Поэтому внутри
// NesApu::step() такты ВСЕГДА делятся по границам выходных сэмплов, а этот
// параметр задаёт размер порции, в которой APU отдаёт управление (и, значит,
// задержку флагов/IRQ APU: 128 тактов ≈ 70 мкс).
// 1 — звать APU на каждую инструкцию 6502 (медленно, точность флагов выше).
#define DENDY_APU_GRANULARITY  128

// ==================== 0.7. РАЗГОН: что можно ускорить и как вернуть ==========
// ПОЧЕМУ ЭТО НЕ ПРО ЗВУК. «Песок»/хрип в игре — это нехватка СКОРОСТИ эмуляции
// (APU не успевает наполнять кольцо, задача I2S добивает музыку тишиной), а не
// тактовые частоты. Поэтому увеличение буферов звука и любой «разгон» ниже дают
// только запас на всплески; лечится же всё строкой `fps emu` = 60,0 в логе
// [GAME] (и `[GAME] profil`/`vremya`, которые объясняют, куда уходит время).
// ЧТО ЗАДАЁТСЯ В КОДЕ (и как вернуть):
//   * DISPLAY_FREQ_WRITE (раздел 2, сейчас 80000000UL = 80 МГц): скорость шины
//     дисплея, ~12 мс на кадр 256x240. Это единственный настоящий «разгон в
//     коде». Выше (100000000UL) часть клонов ST7789 даёт артефакты: проверяйте
//     картинку, при «снеге» верните 80000000UL;
//   * SX1509_I2C_FREQ (раздел 4, 400000): шина кнопок; 400 кГц — предел SX1509,
//     выше ставить бессмысленно;
//   * DENDY_CORE_IRAM / DENDY_CART_IRAM / DENDY_CORE_O3 (0.5 и DendyFast.h):
//     горячий код ядра — в IRAM, активные банки рома — в SRAM. Это самая большая
//     прибавка скорости; если поставить 0, станет заметно медленнее.
// ЧТО ЗАДАЁТСЯ ТОЛЬКО В МЕНЮ Tools И НЕ МЕНЯЕТСЯ КОДОМ:
//   * CPU Frequency -> 240 MHz — максимум для ESP32-S3. В логе это строка
//     [SYS] sbor: «CPU 240 MHz»; 160 МГц даст ~35..40 кадров/с вместо 60;
//   * Debug Level -> None — при Debug/Verbose весь проект собирается с -Og, и
//     эмулятор замедляется в разы (страховка — DENDY_CORE_O3 в DendyFast.h);
//   * Flash Mode -> QIO 80 MHz. «Побольше» (QIO 120 MHz) есть не у всех модулей,
//     это разгон ВНЕ спецификации: при неудаче плата уходит в цикл перезагрузки
//     (спасает только прошивка с зажатым BOOT). ПОЛЬЗЫ ПОЧТИ НЕТ: горячий код уже
//     в IRAM (DENDY_CORE_IRAM = 1), а ром — в SRAM (DENDY_CART_IRAM = 1), во флеш
//     эмулятор почти не обращается; выигрыш заметен только на старте и в меню;
//   * PSRAM -> OPI PSRAM. Частоту (80 МГц) в IDE выбрать НЕЛЬЗЯ: она задаётся
//     загрузчику при сборке образа, то есть менять её = пересобирать ядро ESP32.
//     Кадровые буферы лежат в PSRAM, поэтому это самый реальный предел скорости
//     PPU/вывода, и обойти его из скетча нельзя (см. DENDY_CART_IRAM и
//     DENDY_FRAME_DOUBLE_BUFFER — они уменьшают обращения к PSRAM).
// ==================== 0.2. ТЕСТ ДИСПЛЕЯ (без эмулятора) ======================
// 1 — вместо эмулятора запускать диагностику вывода на LCD (LcdTest.ino):
//     перебор конфигураций панели (частота SPI 80/40/20 МГц, драйвер
//     ST7789/ILI9341/ST7796, invert, rgb_order, размеры) с тест-картинкой.
//     Нужен, чтобы отличить «врёт вывод на экран» от «врёт ядро эмулятора»:
//     на тесте видно, где картинка правильная, а где мусор.
//     0 — обычный режим (эмулятор).
// Подробности и как читать результат — в шапке LcdTest.ino и в README.
#define DENDY_LCD_TEST         0
// -1 — перебирать конфигурации по кругу (6-9 секунд на каждую, BOOT —
// заморозить выбранную); 0..8 — сразу начать с этой конфигурации и заморозить.
#define DENDY_LCD_TEST_CFG     (-1)

// ===================== 1. ФИЗИЧЕСКИЕ ПИНЫ (ESP32-S3 N16R8) ===================
// !! GPIO33..GPIO37 подключены ВНУТРИ чипа к Octal PSRAM (8 МБ) и использовать
//    их нельзя ни для чего. Проверка находится ниже (static_assert).
//
// --- Дисплей ST7789 (SPI2 / FSPI) ---
#define PIN_TFT_SCLK           11   // SCL  (SCK)
#define PIN_TFT_MOSI           12   // SDA  (MOSI)
#define PIN_TFT_CS             10   // CS
#define PIN_TFT_DC             13   // DC
#define PIN_TFT_RST            14   // RES
#define PIN_TFT_BL             21   // BLK  (подсветка, PWM)

// --- Звуковой кодек MAX98357 (I2S) ---
#define PIN_I2S_LRCK           15   // LRC / WS
#define PIN_I2S_BCLK           16   // BCL / BCK
#define PIN_I2S_DOUT           17   // DIN / DOUT (с выхода ESP на вход кодека)
// ВАЖНО (по даташиту MAX98357A): SD — это ВХОД режима, а не «выбор моно».
//   SD < 0.16 В (то есть SD НА GND)  -> усилитель ВЫКЛЮЧЕН (shutdown) — тишина!
//   0.16..0.77 В                     -> (L+R)/2 (нужный нам моно-режим)
//   0.77..1.4 В                      -> только правый канал
//   > 1.4 В                          -> только левый канал
// Внутри чипа на SD стоит подтяжка ~100 кОм к GND, поэтому на модуле Adafruit
// (и большинстве клонов) между SD и VIN есть резистор 1 МОм: SD можно просто
// оставить в ВОЗДУХЕ — тогда получается (L+R)/2. Если резистора нет, поставьте
// 100 кОм (левый канал) или 1 МОм (L+R)/2) между SD и питанием 3.3/5 В.

// --- Расширитель кнопок SX1509 (вторая шина I2C) ---
// SDA -> GPIO8, SCL -> GPIO9 — так подключено на плате (проверено логом: чип
// отвечает адресом 0x3E именно на этом порядке). Если провода SDA/SCL перепутаны,
// при старте сработает автоподбор (SX1509_AUTO_SWAP_PINS) и в мониторе появится
// строка о фактических пинах.
#define PIN_I2C2_SDA           8    // SDA шины I2C №2
#define PIN_I2C2_SCL           9    // SCL шины I2C №2
#define PIN_SX1509_INT         3    // INT от SX1509 (INPUT_PULLUP, FALLING)

// Стек задачи loop() (эмулятор + графическая библиотека). Ядро по умолчанию
// даёт 8192 байта; SET_LOOP_TASK_STACK_SIZE() в скетче поднимает до этого числа.
#define DENDY_LOOP_STACK       16384

// Запрет использования "мёртвых" выводов Octal PSRAM (GPIO33..GPIO37)
#define DENDY_PIN_OK(name, pin) \
  static_assert(((pin) < 33 || (pin) > 37), \
                "Пин " #name " занят Octal PSRAM (GPIO33..37) на ESP32-S3 N16R8")
DENDY_PIN_OK(PIN_TFT_SCLK,   PIN_TFT_SCLK);
DENDY_PIN_OK(PIN_TFT_MOSI,   PIN_TFT_MOSI);
DENDY_PIN_OK(PIN_TFT_CS,     PIN_TFT_CS);
DENDY_PIN_OK(PIN_TFT_DC,     PIN_TFT_DC);
DENDY_PIN_OK(PIN_TFT_RST,    PIN_TFT_RST);
DENDY_PIN_OK(PIN_TFT_BL,     PIN_TFT_BL);
DENDY_PIN_OK(PIN_I2S_LRCK,   PIN_I2S_LRCK);
DENDY_PIN_OK(PIN_I2S_BCLK,   PIN_I2S_BCLK);
DENDY_PIN_OK(PIN_I2S_DOUT,   PIN_I2S_DOUT);
DENDY_PIN_OK(PIN_I2C2_SDA,   PIN_I2C2_SDA);
DENDY_PIN_OK(PIN_I2C2_SCL,   PIN_I2C2_SCL);
DENDY_PIN_OK(PIN_SX1509_INT, PIN_SX1509_INT);

// ============================ 2. ДИСПЛЕЙ ST7789 ==============================
#define DISPLAY_ROTATION       1      // 1 или 3 — альбомная ориентация (320x240)
#define DISPLAY_PANEL_W        240    // ширина панели до поворота
#define DISPLAY_PANEL_H        320    // 320 для 2.0"..2.8", 240 для квадратных 1.3"/1.54"
#define DISPLAY_OFFSET_X       0
#define DISPLAY_OFFSET_Y       0
#define DISPLAY_INVERT         true   // для большинства модулей ST7789 = true
#define DISPLAY_BGR            false  // поменяйте на true, если красный/синий наоборот
// ВНИМАНИЕ: 80 МГц НЕ у всех модулей работают чисто (на длинных проводах и на
// части клонов ST7789 появлялись артефакты/«мешанина» цветов). На ЭТОЙ плате
// 80 МГц прогоняли отдельно — картинка чистая, поэтому и стоит 80000000UL:
// это ~12 мс на кадр, то есть 60 кадров/с на экране (на 40 МГц было ~26 мс и
// потолок ~36 кадров/с). Если после смены прошивки/проводов появятся артефакты —
// верните 40000000UL (скорость САМОЙ игры от этого не зависит, её задаёт
// `fps emu`; меняется только частота обновления картинки на экране).
// Полный перебор частот и драйверов панели — DENDY_LCD_TEST 1.
//
// 40 МГц — это ~26 мс на кадр 256x240 (122 880 байт), то есть потолок ПЕРЕДАЧИ
// ~36 кадров/с. Скорость самой игры от этого не зависит (её задаёт `fps emu`;
// кадр уходит на втором ядре параллельно эмуляции, лишние кадры просто не
// выводятся), но картинка обновляется реже, чем эмулируется. Если конкретный
// модуль и провода тянут больше — поднимите частоту (60000000UL, затем
// 80000000UL) и проверьте картинку: 80 МГц это ~12 мс на кадр, то есть и
// «полные» 60 кадров/с на экране.
#define DISPLAY_FREQ_WRITE     120000000UL
#define DISPLAY_FREQ_READ      16000000UL

// --- Порядок каналов цвета при выводе КАДРА NES ---------------------------------
// Кадровый буфер уходит на экран тем же pushImage(), что и всё остальное, значит
// в нём должен лежать ОБЫЧНЫЙ (логический) RGB565 — ровно такой, какой понимает
// LovyanGFX в fillRect/drawString. Тогда цвета игры совпадают с цветами меню.
// НО: pushImage() с 16-битным буфером отдаёт байты как они лежат в памяти, а
// панели ждут старший байт первым. Поэтому «как есть» (режим 0) на этом железе
// даёт НЕВЕРНЫЕ цвета — проверено на живой плате: небо $22 (сине-голубое,
// слово 6C5F) выходило ЗЕЛЁНЫМ (байты уходили как 5F6C), а режим 2 — розовым.
//   0 — как есть (логический RGB565 без перекодировки)
//   1 — поменять местами байты 16-битного слова (младший <-> старший) ← нужно тут
//   2 — поменять местами поля зелёного и синего (G6 <-> B5)
//   3 — поменять местами поля красного и синего (R5 <-> B5, «BGR»)
// ПОДБИРАТЬ РЕЖИМ ПЕРЕСБОРКОЙ НЕ НУЖНО: в меню и в игре работает «горячая»
// комбинация SELECT + LEFT/RIGHT — режим меняется на лету, а в меню рядом
// рисуются две полосы: сверху КАДРОВЫЙ путь (pushImage), снизу эталон
// LovyanGFX (fillRect). Как только полосы совпали — это и есть нужный режим,
// его значение и имя печатаются в лог (строка [VID] poryadok cvetov).
// Меню (его рисует LovyanGFX) перекодировка не затрагивает.
#define DENDY_COLOR_ORDER      1

// --- ШКАЛА ЯРКОСТИ ПОДСВЕТКИ: ВЕРХ ШКАЛЫ --------------------------------------
// DISPLAY_BRIGHTNESS — это ВЕРХ шкалы ШИМ (0..255), то есть «100 %» в OSD, в меню и
// в кнопке яркости: ступени кнопки заданы в процентах именно от него (см.
// DISPLAY_BR_STEPS_PCT ниже). 255 — настоящий максимум панели. Если на этой плате
// 100 % окажется слишком ярко (ток/нагрев), поставьте здесь 230: тогда «100 %»
// станет прежней яркостью по умолчанию (230/255 ≈ 90 %), а все проценты
// пересчитаются сами — править больше ничего не нужно.
#define DISPLAY_BRIGHTNESS     255
// --- ЯРКОСТЬ ЭКРАНА КНОПКОЙ (вывод 8 SX1509, SX_PIN_BRIGHT) -------------------
// Кнопка переключает яркость по кругу; список и порядок ступеней задаёт
// DISPLAY_BR_STEPS_PCT. Работает И в игре, И в меню. Значение НЕ сохраняется: при
// следующем включении яркость снова DISPLAY_BR_DEFAULT_PCT (так задумано — яркость
// привязана к питанию/разряду батареи, а не к последнему рому).
// Почему в процентах, а не в 0..255: это значение видно на экране (OSD «YARK 75 %»,
// шапка меню) и в логе, и его легко сверить с настройкой, не пересчитывая дважды.
#define DISPLAY_BR_DEFAULT_PCT 70     // яркость при включении, % (1..100)
// Ступени кнопки яркости: по кругу, от меньшей к большей. Начальное значение
// (70 %) в списке быть НЕ обязано: первое нажатие уводит на БЛИЖАЙШУЮ БОЛЬШУЮ
// ступень (70 -> 75), а с самой большой круг замыкается на первую (100 -> 5).
// Список проверяет static_assert в скетче: 2..16 значений, 1..100 %, по возрастанию.
// Ступень 0 % намеренно не поддерживается: ШИМ погасил бы подсветку совсем, и
// вернуть яркость пришлось бы вслепую.
#define DISPLAY_BR_STEPS_PCT   { 5, 15, 25, 50, 75, 100 }
// Пауза между шагами ПЛАВНОГО перехода к новой яркости, мс. Смена яркости — это
// ступенька тока по общему с кодеком питанию (как у включения подсветки), поэтому
// переход размазан на ~8 шагов: скачок 75 % -> 5 % идёт ~50 мс и в динамике не
// слышен. 0 — переключать сразу (обычный регулятор, без плавности).
#define DISPLAY_BR_GLIDE_STEP_MS 6
// --- МЯГКОЕ ВКЛЮЧЕНИЕ ПОДСВЕТКИ (DISPLAY_BL_RAMP_MS) --------------------------
// Подсветка висит на GPIO21 и управляется ШИМ (lgfx::Light_PWM в скетче), поэтому
// яркость можно поднимать плавно. ЗАЧЕМ: подсветка — самый большой потребитель на
// плате, и ступенька 0 -> рабочая яркость (DISPLAY_BR_DEFAULT_PCT) давала бросок
// тока по общему с кодеком питанию; по времени он попадал в первое включение звука
// и слышался щелчком (разбор — «ПЕРВЫЙ ЗВУК ПОСЛЕ ВКЛЮЧЕНИЯ» в блоке 3 «ЗВУК»).
// Плавный подъём растягивает бросок на это время и уводит его из окна первого
// звука: подъём идёт в setupDisplay(), то есть ДО setupAudio() и задолго до джингла.
// Цена: ровно столько миллисекунд добавляется к времени загрузки. Первый полный
// кадр рисуется ДО подъёма, пока экран ещё тёмный (см. backlightSoftStart).
// 0 — как раньше: яркость ставится сразу.
#define DISPLAY_BL_RAMP_MS     300
// Передача кадра на экран.
//   1 — pushImageDMA(): SPI-DMA напрямую из буфера кадра в PSRAM. LovyanGFX
//       (1.2.19) не сбрасывает кэш PSRAM перед таким DMA, поэтому на ESP32-S3
//       DMA может прочитать УСТАРЕВШИЕ строки кадра — картинка «мешается»
//       (это и давало артефакты и «неправильные цвета» по всему экрану).
//   0 — pushImage(): процессор отдаёт пиксели в SPI, читая PSRAM через кэш,
//       поэтому данные всегда корректны. Времени это не добавляет: передача
//       всё равно упирается в скорость SPI (122 КБ при 40 МГц ≈ 24 мс).
#define DENDY_GFX_EXPLICIT_DMA 0      // 0 — pushImage() (надёжно), 1 — pushImageDMA()

// Кадр NES 256x240 выводится 1:1 по центру экрана (альбомная ориентация).
// Ширина экрана в альбомной ориентации равна высоте панели (320 для 240x320).
#define DISPLAY_LANDSCAPE_W    DISPLAY_PANEL_H
#define NES_VIEW_X             ((DISPLAY_LANDSCAPE_W - 256) / 2)   // 32 при 320x240
#define NES_VIEW_Y             0

// ================================ 3. ЗВУК ====================================
// --- ЧАСТОТА ДИСКРЕТИЗАЦИИ (AUDIO_SAMPLE_RATE): опыт «44 100 -> 22 050» ОТМЕНЁН --
// ЗАЧЕМ ПОНИЗИЛИ: сэмплов в секунду вдвое меньше, значит вдвое меньше работы у
// APU и микшера (`apu` в строке [GAME] profil) — это единственная РЕАЛЬНАЯ
// выгода. Вдвое меньше и данных уходит в I2S.
// ЧЕГО ЭТО НЕ ДЕЛАЕТ: не убирает «песок» от нехватки ТЕМПА ЭМУЛЯЦИИ. APU и I2S
// живут в одной и той же секунде, поэтому дефицит остаётся тем же ПРОЦЕНТОМ при
// любой частоте: при `fps emu` = 44 на 22 050 Гц выходит 44 x (22050/60) =
// 16 170 сэмплов/с вместо 22 050 — не хватает тех же 26,7 % (при 44 100 было
// 32 340 вместо 44 100), и задача I2S ровно так же добивает недостающее тишиной.
// Меняется только «характер» дыр: они вдвое реже и вдвое длиннее (щелчки реже,
// провалы заметнее).
// ЧТО СТАНОВИТСЯ ХУЖЕ: Найквист опускается с 22,05 до 11,03 кГц — всё, что APU
// выдаёт в полосе 11..22 кГц (обертоны пульсов, шум LFSR, «металлический» шум),
// теперь заворачивается ПРЯМО в музыку (0..11 кГц), а не в почти неслышимую
// полосу 11..22 кГц. То есть грязи может стать больше, а не меньше. Мягкий ФНЧ
// (DENDY_APU_LOWPASS_HZ) при 22 050 ставить не выше ~8000: 12 000 при Найквисте
// 11 025 уже ничего не даёт.
// ЧТО СМОТРЕТЬ В ЛОГЕ (до и после; DENDY_DEBUG_SERIAL 1, трасса видео 0):
//   * [GAME] fps emu — ГЛАВНОЕ: подошёл к 60,0 (и `apu` в profil упал вдвое) —
//     эксперимент удался; остался 44 — не помогло;
//   * [GAME] sempl/s N iz 44100 — норма ровно 44 100; меньше = та же тишина;
//   * `tishina`/`dyra` растут => дефицит темпа никуда не делся;
//   * поле `hf %` (песок-метр) МЕЖДУ РАЗНЫМИ ЧАСТОТАМИ НЕ СРАВНИВАТЬ: его порог
//     задан долей от частоты сэмплирования (~2 кГц при 44 100 и ~1 кГц при
//     22 050), поэтому при понижении оно вырастет само по себе.
// ВЫСОТА ТОНА И ТЕМП НЕ МЕНЯЮТСЯ: и APU (аккумулятор sampleAcc в тактах CPU), и
// джингл меню (фазовый аккумулятор g_sndStep) считают от AUDIO_SAMPLE_RATE.
// КАК ВЕРНУТЬ: поставьте 44100 и AUDIO_DMA_FRAMES 256 (размеры буферов в СЭМПЛАХ
// при смене частоты вдвое тоже меняются вдвое — иначе поедет задержка в мс).
// Частоты, «согласованные» с 60 кадрами (целое число сэмплов на кадр): 44 100
// (735), 24 000 (400), 22 500 (375), 18 000 (300), 12 000 (200). 22 050 и 11 025
// дают 367,5 и 183,75 — тоже корректно: APU чередует 367/368, дрейфа нет.
// ВЕРНУЛИСЬ НА 44 100 (эксперимент с 22 050 отменён). Что показал опыт: понижение
// частоты экономило всего ~1 мс на кадр в поле `apu` строки [GAME] profil (основная
// цена APU — не сэмплирование, а тактирование каналов каждый такт CPU, оно от
// частоты не зависит), а звук при этом терял полосу: всё выше 11 кГц пропадало,
// пульсы и шум становились «тусклее». «Песок» же лечит НЕ частота, а адаптивный
// темп (AUDIO_ADAPTIVE_RATE) и антиалиасинг (DENDY_APU_ANTIALIAS) — оба работают
// и на 44 100. Размеры буферов в СЭМПЛАХ при возврате удвоены (AUDIO_DMA_FRAMES
// 256), чтобы длительность блока DMA и задержка звука остались прежними.
#define AUDIO_SAMPLE_RATE      44100  // Гц (нынешнее значение; разбор — выше)
#define AUDIO_VOLUME_DEFAULT   50     // громкость при старте (0..100)
#define AUDIO_VOLUME_STEP      5      // шаг кнопок громкости "+" / "-"
// Авто-повтор кнопок громкости (SX_PIN_VOL_UP / SX_PIN_VOL_DOWN) при удержании:
// первый шаг — сразу по нажатию, дальше каждые столько миллисекунд.
#define AUDIO_VOLUME_REPEAT_MS 150
// --- ПЕРВЫЙ ЗВУК ПОСЛЕ ВКЛЮЧЕНИЯ: «прогрев» тракта тишиной --------------------
// СИМПТОМ. Иногда при подаче питания в САМОМ НАЧАЛЕ джингла меню проскакивает
// короткий треск/щелчок. Дальше звук идёт чисто — значит дело не в музыке и не в
// APU (джингл синтезируется сразу на выходной частоте и в APU не заходит).
// ПРИЧИН ТРИ, и лечатся они РАЗНЫМИ настройками (все — ниже):
//   1) первый сэмпл приходит в НЕустоявшийся тракт: кодек MAX98357 только что
//      получил питание (его выходной конденсатор и внутренний ФНЧ ещё заряжаются),
//      ESP32 инициализирует кнопки по I2C (SX1509), читает образ LittleFS (флеш) и
//      ПЕРВЫЙ раз перерисовывает весь экран по SPI;
//   2) СТУПЕНЬКА ТОКА по общему питанию: подсветка включалась сразу на полную
//      (0 -> рабочая яркость, DISPLAY_BR_DEFAULT_PCT), а первая полная отрисовка
//      экрана — это ещё и
//      бросок тока по SPI/панели. Просадка по VIN кодека слышна щелчком, и она
//      попадает в звук «иногда»: загрузка на разных ромах занимает разное время, и
//      всплеск то успевал пройти до джингла, то нет;
//   3) СТУПЕНЬКА САМОГО СИГНАЛА: «тишина -> нота» без нарастания. У джингла меню
//      есть только ~2 мс «наезда» (menuSoundSample), а музыка рома начинается
//      сразу с полного уровня.
// ЧТО ДЕЛАЕМ (все три настройки независимы, любую можно поставить в 0):
//   * AUDIO_START_GUARD_MS — «прогрев» тракта тишиной: I2S включается как обычно
//     (BCLK/LRCK идут непрерывно, в DMA уходит «пустой звук» с дизерингом — см.
//     AUDIO_IDLE_DITHER), но первые AUDIO_START_GUARD_MS миллисекунд в кодек идёт
//     ТОЛЬКО тишина, а первый звук откладывается до конца окна;
//   * AUDIO_FIRST_SOUND_QUIET_MS — «тихое окно» ПОСЛЕ последнего тяжёлого шага
//     загрузки (sndBootBusyMark зовут монтирование LittleFS, NesCore::init, кнопки,
//     скан ромов, чтение рома и первая полная отрисовка). Именно это убирает
//     «иногда»: окно считается от РЕАЛЬНОГО конца всплеска, а не от момента
//     запуска I2S, который может оказаться заметно раньше;
//   * AUDIO_START_FADE_MS — «мягкое включение звука»: первый звук не появляется
//     сразу, а проявляется от нуля за это время (в цифре — считает audioTaskEntry,
//     через который идут и джингл меню, и музыка рома);
//   * DISPLAY_BL_RAMP_MS (блок 2 «ДИСПЛЕЙ») — плавный подъём подсветки: убирает
//     самую большую ступеньку тока из окна первого звука. Тем же способом идёт и
//     смена яркости кнопкой (DISPLAY_BR_GLIDE_STEP_MS) — см. блок 2 «ДИСПЛЕЙ»).
// Логика в скетче: sndStartGuardArm() и sndBootBusyMark() — в setup() (раздел 6);
// джингл меню — menuSoundJingleOnMenuEnter()/menuSoundDeferredJingle() (раздел 6.1);
// старт игры при ROM_AUTORUN_SINGLE — sndStartGuardWait() в runGame (музыка рома —
// тоже «первый звук после включения»).
// ЖЕЛЕЗО, ЧТО КОДУ НЕ ПОДВЛАСТНО. Вывод SD кодека в этой сборке никуда не
// подключён (блок 1 «ФИЗИЧЕСКИЕ ПИНЫ»), поэтому усилитель выходит из shutdown САМ,
// когда драйвер I2S поднимает BCLK/LRCK (в setupAudio), и его собственный щелчок
// включения окнами выше НЕ убирается — только отодвигается от первого звука. Если
// щелчок всё ещё слышен: (а) в коде он лечится ТОЛЬКО управлением SD (завести его
// на свободный GPIO и включать усилитель в тишину), (б) остальное — железо:
// электролит 470..1000 мкФ плюс 0.1 мкФ у VIN кодека, отдельный феррит/LC в его
// питании, «звезда» по земле, провода динамика подальше от проводов SPI.
// СКОЛЬКО СТАВИТЬ. 700 (по умолчанию) — вся загрузка платы с ромом укладывается в
// это время, и звук всё ещё начинается «сразу после включения»; 300 — минимум;
// 0 — выключить «прогрев»: джингл снова играет сразу, как было до этой правки.
#define AUDIO_START_GUARD_MS   700
// «ТИХОЕ ОКНО» ПОСЛЕ ЗАГРУЗОЧНЫХ ВСПЛЕСКОВ (см. причину 2 выше). Каждый тяжёлый
// шаг загрузки зовёт sndBootBusyMark(), и первый звук ждёт ещё столько миллисекунд
// после последнего такого шага. 150 — с запасом на «хвост» просадки питания и на
// запись строки лога в USB-CDC (Serial может ждать буфера до 100 мс); 300 — если
// щелчок всё ещё ловится. 0 — выключить окно.
#define AUDIO_FIRST_SOUND_QUIET_MS 150
// «МЯГКОЕ ВКЛЮЧЕНИЕ ЗВУКА» (см. причину 3 выше): первый звук после включения
// проявляется от нуля за это время. Ручки плавного включения у MAX98357 нет (его
// можно только включить или заглушить выводом SD), поэтому нарастание делается в
// цифре: audioTaskEntry поднимает уровень сэмплов от 0 до полного.
// 150 мс: щелчка нет, а первая нота джингла (523 Гц, 90 мс) слышна целиком;
// 0 — как раньше (ступенькой). Работает ОДИН раз за включение — на первый звук.
#define AUDIO_START_FADE_MS    150
// Сколько МАКСИМУМ ждать разрешения первого звука в «медленном» месте (старт игры
// при ROM_AUTORUN_SINGLE), мс. Взято с запасом от самих окон: если в них случайно
// вписали огромные числа, загрузка игры не встанет колом — дождались и играем.
#define AUDIO_START_GUARD_WAIT_MAX_MS \
  ((int)(AUDIO_START_GUARD_MS + AUDIO_FIRST_SOUND_QUIET_MS + 500))
// --- РАЗМЕРЫ БУФЕРОВ ЗВУКА: что они дают и чего НЕ дают -----------------------
// Буферизация звука идёт в три уровня (от выхода к источнику):
//   1) DMA I2S    = AUDIO_DMA_BUF_COUNT * AUDIO_DMA_FRAMES сэмплов. Это то, что
//      кодек УЖЕ играет, то есть чистая ЗАДЕРЖКА звука, а не «запас под музыку»;
//   2) кольцо APU = AUDIO_RING_SIZE сэмплов (NesApu::RING_SIZE). Сюда APU кладёт
//      сэмплы, отсюда задача I2S их забирает (NesCore::drainAudio);
//   3) «подушка»  = AUDIO_PRIME_SAMPLES (AUDIO_PRIME_FRAMES кадров звука) —
//      предзаполнение кольца тишиной при старте рома (см. ниже).
// ГЛАВНОЕ: НИ ОДИН ИЗ ЭТИХ БУФЕРОВ НЕ ЛЕЧИТ НЕХВАТКУ СКОРОСТИ ЭМУЛЯТОРА. Если
// эмулятор идёт 44 кадра/с вместо 60, APU отдаёт 44/60 от нужного, то есть при
// 44 100 Гц — 32 340 сэмплов/с вместо 44 100 (дефицит 26,7 %) — и сколько бы
// места ни было в буферах, задача I2S
// всё равно добьёт недостающее тишиной (в логе `tishina`/`dyra`, на слух —
// «песок»). Буферы сглаживают только ВСПЛЕСКИ: кадр пришёл позже
// (опрос кнопок по I2C, печать в Serial, пачка кадров при DENDY_MAX_FRAME_SKIP).
// Поэтому если в игре растут `tishina`/`dyra` — сначала смотрите `fps emu` в
// строке [GAME] (должно быть 60,0) и `[GAME] profil`/`vremya`, и только потом
// трогайте размеры буферов.
// Задержка звука от этих буферов (нынешняя частота 44 100 Гц):
//   DMA 4 x 256 сэмплов = 23 мс (один блок 5,8 мс) — это то, что кодек УЖЕ играет;
//   кольцо 2048 = 46 мс (запас, а не задержка: в ровном режиме регулятор держит
//     в нём ~900 сэмплов ≈ 21 мс, см. AUDIO_RATE_MID);
//   «подушка» 1 кадр (AUDIO_PRIME_FRAMES = 1) ≈ 17 мс.
// Итого около 45 мс — столько звук отстаёт от картинки. Нужен запас ПОБОЛЬШЕ под
// всплески — поднимайте AUDIO_DMA_BUF_COUNT до 6..8 (каждый буфер +5,8 мс); нужен
// отклик побыстрее — снижайте AUDIO_DMA_BUF_COUNT до 3 и AUDIO_PRIME_FRAMES до 0.
// РАЗМЕР ОДНОГО DMA-БУФЕРА. Держите не больше ~1024 сэмплов: каждый буфер это
// память внутренней SRAM (256 сэмплов стерео 16 бит = 1 КБ) и та же задержка.
// 256 взято под 44 100 Гц, чтобы ДЛИТЕЛЬНОСТЬ блока осталась 5,8 мс (при 22 050
// это же время давали 128 сэмплов). Частота и размер меняются ТОЛЬКО вместе:
// иначе поедет задержка в миллисекундах.
#define AUDIO_DMA_FRAMES       256    // сэмплов в одном DMA-буфере (5,8 мс при 44 100)
// ЧИСЛО БУФЕРОВ = ЗАДЕРЖКА ЗВУКА (и «подушка» под всплески задачи I2S).
// Было 4 (23 мс) — после перевода горячего кода в IRAM и полного 60 кадров/с
// запас в 23 мс стал избыточным: с 3 (17 мс) звук приходит к динамику на 5,8 мс
// раньше, а задача пишет блок каждые 5,8 мс и всё равно имеет два блока запаса.
// Если по строке [SND] видно растущие `tishina`/`oshek` (DMA пустел) — верните 4.
#define AUDIO_DMA_BUF_COUNT    3      // количество DMA-буферов (5,8 мс каждый)
// Кольцевой буфер сэмплов живёт в ядре APU: NesApu::RING_SIZE = AUDIO_RING_SIZE.
// Размер обязан быть степенью двойки (индексы считаются маской) и вмещать
// «подушку» вместе с одним блоком DMA — за этим следит static_assert ниже.
// Задача I2S забирает сэмплы через NesCore::drainAudio().
#define AUDIO_RING_SIZE        2048   // размер кольца APU (= NesApu::RING_SIZE), 46 мс
//
// --- «ПОДУШКА» ЗВУКА: почему в ИГРЕ был ХРИП (и как это вылечено) --------------
// Задача I2S пишет в DMA РОВНО столько сэмплов, сколько забрала из кольца, а не
// «всегда 256, а недобор добить нулями». Раньше было второе, и получалось вот что.
// APU отдаёт сэмплы НЕ ровным потоком: 735 сэмплов на кадр набираются за время
// эмуляции кадра, а затем наступает пауза до границы следующего кадра (у нас это
// ~1,7 мс из 16,7). В момент такой паузы в кольце оказывается ~220 сэмплов вместо
// 256 — и «добивка» вставляла в СЕРЕДИНУ музыки дырку ~0,8 мс примерно раз в кадр
// (~57 раз в секунду). На слух это и есть хрип/«песок» в игре, хотя игра идёт ровно
// 60,0 кадров/с, а в логе кольцо показывает `koltso APU 0/2048` (задача вычерпывала
// его досуха) и `tishina 0` (полностью пустым оно всё же не было — потому в
// строке [GAME] и не было видно проблемы). В МЕНЮ джингл звучал чисто, потому что
// serviceMenuSound() держит кольцо полным и недобора там не бывает.
// Что теперь:
//   1) блок в DMA пишется того размера, сколько сэмплов реально есть; темп задаёт
//      сам I2S (DMA 4 x 256 сэмплов = 23 мс при 44 100 Гц сглаживает «рваный» темп);
//   2) перед стартом игры кольцо предзаполняется тишиной (AUDIO_PRIME_SAMPLES) —
//      это «подушка» на дрожание продюсера, ровно как у меню;
//   3) нули уходят в кодек только если кольцо пусто ЦЕЛИКОМ (меню, пауза), и то
//      коротким блоком AUDIO_FEED_IDLE (~1,5 мс).
// Проверка по логу после заливки: в строке [SND]/[GAME] поле `blok min/max` должно
// показывать около AUDIO_DMA_FRAMES, а не AUDIO_FEED_IDLE и не 1, а `tishina`/`dyra`
// стоять на месте. Если же они растут — эмулятор не выдаёт 60 кадров/с (см. в
// начале блока 3 «РАЗМЕРЫ БУФЕРОВ ЗВУКА»): буферы это не лечат, лечит `fps emu`.
#define AUDIO_PRIME_FRAMES     1      // «подушка»: сколько кадров звука предзалить
// 1 кадр = 735 сэмплов (~17 мс при 44 100 Гц) — столько звука лежит в кольце к
// началу игры.
// 0 (как было раньше) означало, что кольцо в среднем ПУСТО: сэмплы APU отдаёт
// пачками по границам кадров, задача I2S вычерпывает кольцо досуха, и любое
// дрожание продюсера (кадр пришёл позже, опрос кнопок по I2C, печать в Serial)
// сразу давало вставку тишины — это и есть `tishina`/«песок». Теперь у задачи есть
// запас, и по нему же регулятор адаптивного темпа (AUDIO_ADAPTIVE_RATE ниже) видит,
// что кольцо не «лежит на дне», и может измерять темп продюсера точно.
#define AUDIO_FEED_IDLE        64     // сэмплов тишины, когда кольцо пусто целиком
// «ПУСТОЙ ЗВУК» (держит MAX98357 активным). Что делает выход усилителя живым —
// это НЕПРЕРЫВНЫЕ BCLK/LRCK, и их даёт сам драйвер I2S: задача audioTaskEntry
// пишет блок за блоком даже тогда, когда в кольце нет ни одного сэмпла (меню,
// пауза, загрузка рома), поэтому тактирование не прекращается никогда и после
// 44 мс «тишины по данным» усилитель НЕ уходит в shutdown.
//   Но цифровой НОЛЬ вI2S — это не «пусто», а «постоянный уровень»: у некоторых
// сборок MAX98357 (и любой УНЧ с DC-смещением) на переходе «долгий ноль ->
// первый звук» слышен щелчок. Поэтому при 1 в пустой блок кладётся ±1 LSB
// (ниже −90 дБ, не слышно), и выход всё время чуть «шевелится».
//   0 — как раньше: точные нули.
#define AUDIO_IDLE_DITHER      1
// 64 при 44 100 Гц = 1,45 мс — та же «дырка», что давали 32 при 22 050, то есть
// при возврате на 44 100 размер в СЭМПЛАХ надо было удвоить.
//
// --- АДАПТИВНЫЙ ТЕМП ЗВУКА: «песок» без 60 кадров/с ---------------------------
// ПРОБЛЕМА. Если эмулятор идёт медленнее приставки (`[GAME] fps emu` 49,4 вместо
// 60,0), APU отдаёт 49,4/60 от нужного числа сэмплов — при 44 100 Гц это ~36 300
// сэмплов/с вместо 44 100. Задача I2S обязана добить разницу тишиной: в логе это
// `tishina`/`dyra`, на слух — «песок» (в музыку ~127 раз в секунду вставляется
// дырка 1,45 мс). Это дефицит ВРЕМЕНИ, а не сэмплов, поэтому НИ частота
// дискретизации, НИ размеры буферов его не лечат (см. блок «РАЗМЕРЫ БУФЕРОВ
// ЗВУКА» выше: он и не обещал) — лечит только темп: либо 60 кадров/с, либо
// растяжение (см. ниже).
// РЕШЕНИЕ. Задача I2S больше не «добивает» недостающее тишиной, а РАСТЯГИВАЕТ то,
// что есть: сэмплы читаются из кольца с дробным шагом (линейная интерполяция,
// NesApu::drainResampled), а шаг регулятор ИЗМЕРЯЕТ по продюсеру — сколько сэмплов
// APU дал за окно, таков и шаг. Коэффициент получается ровно во столько раз, во
// сколько эмулятор медленнее приставки: при 49,4 кадрах/с — 0,823, то есть музыка
// играет на 21 % медленнее и примерно на 3,4 полутона ниже. Это НЕ потеря: игра и
// сама идёт 49,4 кадра/с, поэтому теперь звук впервые совпадает по темпу с
// картинкой, и главное — в музыке больше НЕТ дырок («песка»).
// КОГДА ЭМУЛЯТОР УСПЕВАЕТ (60,0 кадров/с) измеренный шаг равен ровно 1:1, и сэмплы
// уходят в кодек бит в бит (как раньше). «Подушка» (AUDIO_PRIME_FRAMES) держит в
// кольце ~17 мс звука, поэтому короткие всплески (опрос кнопок по I2C, печать в
// Serial, пачка кадров при DENDY_MAX_FRAME_SKIP) гасятся запасом, а не тишиной.
// В ЛОГЕ: поле `temp` в строке [SND] — шаг в промилле (1000 = 1:1, 823 = звук
// растянут в 1,215 раза = эмулятор идёт 49,4 кадра/с), `golod` — сколько сэмплов
// пришлось «зажать» на последнем уровне (кольцо пусто даже с растяжением; при
// живом эмуляторе 0, и расти не должно).
// КАК ВЕРНУТЬ СТАРОЕ ПОВЕДЕНИЕ: AUDIO_ADAPTIVE_RATE = 0 (тогда задача I2S снова
// вставляет AUDIO_FEED_IDLE тишины, и при fps < 60 слышен «песок»).
#define AUDIO_ADAPTIVE_RATE    1
// --- ТЕМП ЭМУЛЯТОРА ДЛЯ ЗВУКА: ЧЕМ ИЗМЕРЯТЬ (и почему прежняя оценка «плыла») --
// СИМПТОМ, КОТОРЫЙ ЭТО ЛЕЧИТ: «звук совсем немного расплывается», хотя `temp` в
// строке [SND] стоит около 1000 (то есть растяжения почти нет).
// ПРИЧИНА. Регулятор (NesApu::drainResampled) оценивал темп продюсера ПО КОЛЬЦУ:
// за окно AUDIO_RATE_WIN блоков брал «сколько сэмплов APU положил в кольцо»
// (prodAcc) и делил на «сколько вывели мы» (consAcc). В среднем это верно, но APU
// отдаёт свои сэмплы НЕРАВНОМЕРНО по времени: 735 штук (в PAL — 882) он отдаёт по
// ходу кадра, а в промежутке между кадрами (игровой цикл ЖДЁТ границу кадра,
// frameLimiter) продюсер молчит. Окно = 16 x 256 = 4096 выходных сэмплов = 5,57
// кадра, поэтому в него попадает то 5 целых кадров, то 6, и измеренное отношение
// гуляет на проценты (крайний случай — «вся пачка кадра одним куском» — дал бы от
// 3675/4096 = 0,897 до 4410/4096 = 1,077, то есть ±9 %). Шаг чтения
// уезжал в пределах AUDIO_RATE_SLEW_Q16 (±2 % за окно, ~10 раз в секунду), а
// мёртвая зона иногда возвращала его ровно к 1:1. На слух это медленное дрожание
// высоты тона на единицы-десятки центов, а НЕ дефицит темпа — поэтому его и не
// было видно в `temp` (там 995..1000).
// РЕШЕНИЕ. Темп берём из НЕПРЕРЫВНОЙ величины — фактического периода кадра по
// стен-часам (micros() в runGame). Раз в AUDIO_PRODUCER_WIN_FRAMES кадров скетч
// публикует в APU отношение «номинальный период / фактический» (Q16,
// NesApu::setProducerRatioQ16), а APU берёт его базой шага чтения. Ошибка такой
// оценки падает как 1/число кадров: 16 кадров (~0,27 с) — ~0,1 %, секунда —
// ~0,01 %, и кадровые пачки APU ей не мешают ВООБЩЕ (она про время, а не про
// сэмплы). Оценка по кольцу остаётся только страховкой: (1) как запасной вариант,
// пока скетч ничего не публиковал; (2) lowSum/highSum — «кольцо лежит на дне» /
// «кольцо под завязку» (там прямая оценка слепа).
#define AUDIO_PRODUCER_WIN_FRAMES 16  // кадров в окне измерения периода кадра
#define AUDIO_PRODUCER_EMA_SHIFT  2   // сглаживание отношения в APU (окон публикации)
#define AUDIO_RATE_WIN         16     // блоков DMA в окне измерения темпа (~93 мс)
#define AUDIO_RATE_FLOOR       64     // «кольцо лежало на дне»: сэмплов (порог поправки)
// Середина рабочей зоны кольца (между «дном» и «под завязку»): к ней подтягивается
// регулятор, чтобы из-за квантования шага в Q16 кольцо не сползало к краю.
#define AUDIO_RATE_MID         ((AUDIO_RATE_FLOOR + (AUDIO_RING_SIZE - AUDIO_DMA_FRAMES)) / 2)
#define AUDIO_RATE_MIN_Q16     32768  // не медленнее 0,5 (растяжение 2:1) — ниже уже «плывёт»
#define AUDIO_RATE_MAX_Q16     66191  // не быстрее 1,01 (сжатие): кольцо не должно быть полным
// --- МЁРТВАЯ ЗОНА И ОГРАНИЧЕНИЕ СКОРОСТИ ИЗМЕНЕНИЯ ШАГА -----------------------
// ПОЧЕМУ ЭТО ПОНАДОБИЛОСЬ (симптом: «звук иногда чуть плывёт, некоторые звуки
// запаздывают»). Регулятор выше считает шаг по ИЗМЕРЕННОМУ темпу продюсера и
// подправляет его по заполнению кольца. Обе поправки хороши как СТРАХОВКА, но
// как «тонкая настройка» они опасны:
//   * поправка по «кольцо лежало на дне» (fillMin) срабатывала от ОДНОГО блока
//     окна, в котором кольцо успело показать мало сэмплов (обычный всплеск:
//     загрузка рома, чтение кнопок, печать в Serial), и давала до −6 % темпа
//     НА ВСЁ СЛЕДУЮЩЕЕ окно (~93 мс) — это слышно как «нота подсела и вернулась»;
//     хуже всего было В НАЧАЛЕ игры: fillMin обнулялся в reset(), и первый же
//     блок окна давал поправку вниз на 6,25 % (музыка стартовала ниже тона и
//     «подтягивалась» вверх первые ~0,1 с). Теперь вместо крайних значений окна
//     копится СУММА «глубины» по блокам (NesApu::lowSum/highSum), то есть в
//     поправку идёт СРЕДНЯЯ глубина за окно: одиночный провал — доли процента
//     (на слух ничего), а настоящее «кольцо лежит на дне» — полная поправка;
//   * сам шаг мог измениться скачком на несколько процентов между окнами.
// Мёртвая зона (шаг = РОВНО 1:1, сэмплы уходят бит в бит, интерполяции нет) и
// ограничение изменения шага на окно убирают «плавание», не мешая страховке:
// при реальном замедлении эмулятора шаг едет к нужному значению за пару окон.
#define AUDIO_RATE_DEADBAND_Q16   4    // |шаг−1:1| ≤ 4/65536 (0,006 %) -> ровно 1:1
#define AUDIO_RATE_SLEW_Q16    1310    // максимум ±2 % шага за одно окно измерения
// ЯДРО задачи вывода звука. Эмулятор (loopTask) работает на ядре 1, передача
// кадра на экран — на ядре 0 (DENDY_PUSH_TASK_CORE ниже), поэтому задача I2S
// стоит на ядре 0: там её сосед — только задача SPI-вывода, которая почти всё
// время ждёт DMA. Раньше задача звука жила на ОДНОМ ядре с эмулятором, и каждое
// её пробуждение (забрать кольцо, скопировать блок в стерео, посчитать «песок-
// метр» по каждому сэмплу — это ~1 млн операций в секунду) отбирало время у
// кадра прямо внутри бюджета 16,67 мс: в логе это видно как `hudshij` заметно
// больше `emu ms/kadr` (ровная эмуляция + всплески). Приоритет звука выше
// (AUDIO_TASK_PRIO 4 против DENDY_PUSH_TASK_PRIO 3): пропуск звука хуже, чем
// кадр, задержанный на доли миллисекунды. Если на вашей плате от этого начнёт
// «дёргаться» картинка (`na ekran` меньше `otdano` в строке [GAME]) — верните 1.
#define AUDIO_TASK_CORE        0      // ядро, на котором крутится задача I2S
#define AUDIO_TASK_PRIO        4
#define AUDIO_TASK_STACK       4096   // стек задачи вывода звука (байт)
// Звук меню: пока ром не запущен, эмулятор молчит — и непонятно, «звука нет»
// или сломан тракт (I2S/кодек). При 1 меню играет свой 8-битный джингл и
// «клики» по списку через ТОТ ЖЕ тракт (кольцо APU -> audioTaskEntry -> I2S),
// так что слышимый джингл сразу подтверждает исправность звука.
#define DENDY_MENU_SOUND       1

// --- КАЧЕСТВО ЗВУКА APU: антиалиасинг и «аналоговый» ФНЧ ----------------------
// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Каналы 2A03 — ступенчатые сигналы, которые меняются
// на тактовой CPU (1,79 МГц), а сэмпл берётся AUDIO_SAMPLE_RATE раз в секунду.
// Если брать МГНОВЕННОЕ значение канала (как было раньше), фронт прямоугольника
// «округляется» до ближайшего сэмпла: у ноты 4 кГц (период 28 тактов CPU) на
// период приходится ~6 сэмплов, скважность дрожит на ±17 % — это слышно как
// ровный широкополосный «песок» поверх музыки. Плюс всё, что APU выдаёт выше
// половины частоты сэмплирования (22,05 кГц при 44 100 и 11,03 кГц при 22 050 —
// шум LFSR — до 447 кГц, треугольник — до 55 кГц: чем ниже частота, тем БОЛЬШЕ
// этого заворачивается обратно в слышимый диапазон).
// При 1 сэмпл = СРЕДНЕЕ по окну (интеграл по 40/41 такту CPU при 44 100 и 81/82
// при 22 050). Для ступенчатого
// сигнала это антиалиасинг-фильтр «box» с нулём ровно на AUDIO_SAMPLE_RATE: положение
// фронта сохраняется с точностью до такта CPU (фронт становится наклоном в один
// сэмпл), а не округляется до сетки сэмплов. Высота тона и темп НЕ меняются —
// меняется только чистота звука.
#define DENDY_APU_ANTIALIAS    1
// 0 — вернуться к мгновенному значению канала (для сравнения «на слух»).
//
// Мягкий ФНЧ на выходе микшера — модель аналогового тракта приставки: у живого
// NES/Dendy срез порядка 12..14 кГц, поэтому через телевизор они звучат мягче
// эмулятора (два каскада однополюсного ФНЧ = 12 дБ/окт).
//   0      — выключено: звук ярче и «злее» (по умолчанию — как было);
//   12000  — мягче, ближе к приставке через телевизор;
//   16000  — почти незаметно.
#define DENDY_APU_LOWPASS_HZ   0

// ============================ 3.1. ТАЙМИНГИ ЭМУЛЯЦИИ =========================
// --- Регион приставки и ЧАСТОТА КАДРОВ ---------------------------------------
// Главная величина здесь одна — DENDY_FPS_MILLI (кадров в секунду × 1000). Из
// неё ВЫВЕДЕНО всё остальное: период кадра (DENDY_FRAME_US_NUM/DEN), тактовая
// 2A03 (DENDY_CPU_HZ) и, значит, число сэмплов APU на кадр. Поэтому «честные
// 60 кадров в секунду» проверяются одним числом в логе ([SYS] region и
// [GAME] fps emu), и подкрутить одно число мимо другого уже нельзя — за этим
// следит static_assert в конце блока (если что-то не сойдётся, сборка упадёт
// с понятным текстом, а не «игра вдруг поехала»).
//
// DENDY_REGION_PAL: 0 — NTSC 60 Гц (стандарт, под него сделано почти всё),
//                   1 — PAL 50 Гц (европейская приставка, 312 строк в кадре).
// NTSC: кадр 262 строки × 341 точка = 89 342 точки, 1 такт CPU = 3 точки (12:4).
// PAL : кадр 312 строк × 341 точка = 106 392 точки, 1 такт CPU = 16/5 = 3,2.
// Почему в PAL игра идёт на 16,7 % медленнее (это свойство ОРИГИНАЛА, а не
// эмулятора): за кадр ром выполняет больше тактов CPU, а VBlank — к которому
// привязана логика почти всех игр — наступает 50 раз в секунду вместо 60.
// Значение 1 нужно только для PAL-адаптированных (европейских) ромов, иначе
// они идут примерно на 20 % быстрее оригинала.
// КАК ЭТО ЧИТАЕТСЯ В ЛОГЕ: PAL даёт в строке [GAME] РОВНО `fps emu ~ 50.0`,
// NTSC — РОВНО `60.0`. Любое «некруглое» число (38, 42, 55) означает совсем
// другое: эмулятор не успевает считать кадры (см. [SYS] region и [GAME] vremya).
// ВАЖНО (v1.1): регион теперь можно СМЕНИТЬ БЕЗ ПЕРЕСБОРКИ — в меню есть
// настройка «TV: AUTO / NTSC / PAL» (кнопка на выводе 4 SX1509, см.
// SX_PIN_REGION в блоке 4 «КНОПКИ»). Поэтому ОБА набора таймингов определены
// всегда (переключателю они нужны одновременно), а DENDY_REGION_PAL задаёт
// только тот, с которого прошивка стартует (его же проверяют static_assert'ы
// ниже — они гарантируют, что формулы блока сошлись для региона по умолчанию).
#define DENDY_REGION_PAL   0

// Режим выбора региона (настройка меню; хранится в файле REGION_FILE на LittleFS):
//   AUTO — по заголовку рома (байты 9/10/12 iNES: помечен ли образ как PAL);
//   NTSC / PAL — принудительно, для ромов с «неправильным» или пустым заголовком.
#define DENDY_RMODE_AUTO   0
#define DENDY_RMODE_NTSC   1
#define DENDY_RMODE_PAL    2

// Точек PPU в строке — одинаково у NTSC и PAL.
#define DENDY_PPU_DOTS_PER_LINE   341

// --- Оба региона: значения таймингов (нужны ОДНОВРЕМЕННО, см. выше) -----------
#define DENDY_NTSC_FPS_MILLI     60000ull  // 60,000 кадра/с РОВНО
#define DENDY_NTSC_LINES         262       // строк в кадре
#define DENDY_NTSC_CPU_PER_PPU   1         // 1 такт CPU = 3 точки PPU (12:4)
#define DENDY_NTSC_PPU_PER_CPU   3
#define DENDY_NTSC_FRAME_US_NUM  50000     // период кадра = 50 000/3 = 16 666,67 мкс
#define DENDY_NTSC_FRAME_US_DEN  3
#define DENDY_NTSC_NAME          "NTSC 60 Hz (262 stroki)"

#define DENDY_PAL_FPS_MILLI      50000ull  // 50,000 кадра/с РОВНО
#define DENDY_PAL_LINES          312       // строк в кадре
#define DENDY_PAL_CPU_PER_PPU    5         // 1 такт CPU = 16/5 точки PPU (16:5)
#define DENDY_PAL_PPU_PER_CPU    16
#define DENDY_PAL_FRAME_US_NUM   20000     // период кадра = 20 000/1 = 20 000 мкс
#define DENDY_PAL_FRAME_US_DEN   1
#define DENDY_PAL_NAME           "PAL 50 Hz (312 strok)"

// Регион по УМОЛЧАНИЮ (старт прошивки, static_assert'ы, строка [SYS] region).
#if DENDY_REGION_PAL
  #define DENDY_FPS_MILLI     DENDY_PAL_FPS_MILLI
  #define DENDY_PPU_LINES     DENDY_PAL_LINES
  #define DENDY_CPU_PER_PPU   DENDY_PAL_CPU_PER_PPU
  #define DENDY_PPU_PER_CPU   DENDY_PAL_PPU_PER_CPU
  #define DENDY_FRAME_US_NUM  DENDY_PAL_FRAME_US_NUM
  #define DENDY_FRAME_US_DEN  DENDY_PAL_FRAME_US_DEN
  #define DENDY_REGION_NAME   DENDY_PAL_NAME
#else
  #define DENDY_FPS_MILLI     DENDY_NTSC_FPS_MILLI
  #define DENDY_PPU_LINES     DENDY_NTSC_LINES
  #define DENDY_CPU_PER_PPU   DENDY_NTSC_CPU_PER_PPU
  #define DENDY_PPU_PER_CPU   DENDY_NTSC_PPU_PER_CPU
  #define DENDY_FRAME_US_NUM  DENDY_NTSC_FRAME_US_NUM
  #define DENDY_FRAME_US_DEN  DENDY_NTSC_FRAME_US_DEN
  #define DENDY_REGION_NAME   DENDY_NTSC_NAME
#endif

// Последняя (предрисуночная) строка кадра: на ней PPU сбрасывает флаги.
#define DENDY_PPU_PRERENDER       (DENDY_PPU_LINES - 1)
// Точек PPU за кадр: NTSC 89 342, PAL 106 392.
#define DENDY_PPU_DOTS_PER_FRAME  (DENDY_PPU_LINES * DENDY_PPU_DOTS_PER_LINE)
// Тактовая частота 2A03, при которой кадр длится РОВНО 1/FPS секунды:
//   CPU_Гц = FPS × точек_за_кадр × CPU_PER_PPU / PPU_PER_CPU
// NTSC: 60,000 × 89 342 / 3  = 1 786 840 Гц (у живой NTSC 1 789 773 — на 0,16 %)
// PAL : 50,000 × 106 392/3,2 = 1 662 375 Гц (у живой PAL 1 662 607 — на 0,014 %)
// Никаких «быстрых математик»: и скорость игры, и высота тона задаются именно
// этой парой «частота кадров + тактовая», поэтому игра идёт ровно как на
// приставке (разница 0,16 % не видна и не слышна). Побочная выгода: сэмплов APU
// на кадр выходит РОВНО AUDIO_SAMPLE_RATE/FPS — 735 при 60 кадрах/с и 882 при
// 50, то есть APU и I2S идут секунда в секунду. До этой правки 59,94 кадра/с
// при NTSC-тактной давали дефицит ~117 сэмплов в секунду: кольцо APU медленно
// пустело, и музыка раз в ~11 секунд «щёлкала».
// --- ЧЕСТНЫЕ 60/50: ПОЧЕМУ РОВНО 60,000 И 50,000 (а не 60,0988, как у живой NTSC)
// Живая приставка: NTSC 60,0988 кадра/с (2A03 1 789 773 Гц, PPU 5 369 318 Гц,
// 89 342 точки в кадре), PAL 50,007 кадра/с (2A03 1 662 607 Гц). У нас ровно
// 60,000 и 50,000 — и это не «приблизительность», а следствие того, что весь
// тайминг выведен из ДВУХ целых: тактовой 2A03 и периода кадра. Ограничение
// видно прямо из формулы выше (CPU:PPU = 1:3):
//   DENDY_CPU_HZ = FPS_MILLI x точек_в_кадре / (1000 x 3)
// при 89 342 точках делимость выполняется только для FPS_MILLI, кратных 1500
// (60 000, 58 500, 61 500, ...), а «консольные» 60 099 в них не попадают: вышло
// бы 1 789 788,3 Гц — ДРОБНАЯ тактовая. Точная скорость приставки требует либо
// дробной тактовой, либо дробных границ кадра в микросекундах и рациональной
// арифметики в горячем пути (шаг CPU->PPU и счётчик сэмплов APU: сэмпл стал бы
// 40,5178 такта вместо целого аккумулятора). Разница 0,16 % (NTSC) и 0,014 % (PAL)
// — это 2,8 и 0,24 цента по высоте тона и та же доля в темпе музыки: не слышно
// ни на слух, ни в сравнении с записью приставки (у NTSC-игр и самих ромов
// тайминги разъезжаются сильнее).
// КАК ПРОВЕРИТЬ, ЧТО ИДЁТ ИМЕННО СТОЛЬКО: поле `fps emu` в строке [GAME] и
// `[GAME] vremya ... na kadr N mks` (должно быть 16667 мкс при 60 Гц и 20000 при
// 50) — плюс `temp` в [SND] (1000 = 1:1, то есть APU и I2S идут секунда в секунду).
// ВАЖНО ПРО ЧИСЛА 45 и 55: это ПОРОГИ ТРЕВОГИ в логе («эмулятор не дотягивает»,
// для PAL и NTSC соответственно), а НЕ рабочая частота. Цель — 60,000/50,000.
#define DENDY_CPU_HZ  ((uint32_t)(DENDY_FPS_MILLI * DENDY_PPU_DOTS_PER_FRAME \
                       * DENDY_CPU_PER_PPU / (DENDY_PPU_PER_CPU * 1000ull)))
// Тактов CPU в кадре (дробное: остаток «живёт» в позиции PPU) — потолок для
// защиты от незаканчивающегося кадра в NesCore::runFrame().
#define DENDY_FRAME_CYCLES  (DENDY_PPU_DOTS_PER_FRAME * DENDY_CPU_PER_PPU \
                             / DENDY_PPU_PER_CPU)
// --- То же для ОБОИХ регионов: этими числами ядро пользуется, когда регион
// переключён в меню (NesCore::setRegion -> NesPpu::setRegion / NesApu::setRegion).
// Выведены теми же формулами, что и выше, — «подкрутить мимо» нечего.
#define DENDY_NTSC_PPU_DOTS_PER_FRAME (DENDY_NTSC_LINES * DENDY_PPU_DOTS_PER_LINE)
#define DENDY_PAL_PPU_DOTS_PER_FRAME  (DENDY_PAL_LINES  * DENDY_PPU_DOTS_PER_LINE)
#define DENDY_NTSC_CPU_HZ \
  ((uint32_t)(DENDY_NTSC_FPS_MILLI * DENDY_NTSC_PPU_DOTS_PER_FRAME \
              * DENDY_NTSC_CPU_PER_PPU / (DENDY_NTSC_PPU_PER_CPU * 1000ull)))
#define DENDY_PAL_CPU_HZ \
  ((uint32_t)(DENDY_PAL_FPS_MILLI * DENDY_PAL_PPU_DOTS_PER_FRAME \
              * DENDY_PAL_CPU_PER_PPU / (DENDY_PAL_PPU_PER_CPU * 1000ull)))
#define DENDY_NTSC_FRAME_CYCLES \
  (DENDY_NTSC_PPU_DOTS_PER_FRAME * DENDY_NTSC_CPU_PER_PPU / DENDY_NTSC_PPU_PER_CPU)
#define DENDY_PAL_FRAME_CYCLES \
  (DENDY_PAL_PPU_DOTS_PER_FRAME * DENDY_PAL_CPU_PER_PPU / DENDY_PAL_PPU_PER_CPU)
// Самопроверка тех же чисел для «второго» региона (для региона по умолчанию
// это уже сделано выше): 1 786 840 Гц / 29 780 тактов и 1 662 375 Гц / 33 247.
static_assert(DENDY_NTSC_CPU_HZ == 1786840u && DENDY_PAL_CPU_HZ == 1662375u,
              "регион NTSC/PAL: тайминги блока 3.1 DendyConfig.h не сходятся "
              "(частота кадров × точки в кадре × CPU:PPU)");
static_assert(DENDY_NTSC_FRAME_CYCLES == 29780u &&
              DENDY_PAL_FRAME_CYCLES == 33247u,
              "регион NTSC/PAL: тактов CPU в кадре не сходится — проверьте "
              "блок 3.1 DendyConfig.h");
// Период кадра целыми микросекундами и частота «как есть» — ТОЛЬКО для логов и
// подсказок: сам цикл игры считает границы кадров ДРОБЬЮ NUM/DEN (см.
// nextFramePeriodUs() в скетче), иначе за кадр набегала бы 1 мкс ошибки.
#define DENDY_FRAME_US  ((DENDY_FRAME_US_NUM + DENDY_FRAME_US_DEN / 2) \
                         / DENDY_FRAME_US_DEN)
#define DENDY_FPS       (DENDY_FPS_MILLI / 1000.0f)

// --- Самопроверка: выведенные числа обязаны быть ЦЕЛЫМИ -----------------------
// Ошибка компиляции здесь = в этом блоке подкрутили одно число мимо другого
// (например, поменяли строки в кадре, но не пересчитали тактовую 2A03 или
// период кадра). Это лучше, чем узнать об этом по «поехавшей» игре.
static_assert((DENDY_FPS_MILLI * DENDY_PPU_DOTS_PER_FRAME * DENDY_CPU_PER_PPU)
              % (DENDY_PPU_PER_CPU * 1000ull) == 0,
              "DENDY_CPU_HZ не целое: FPS/строки/точки/соотношение CPU:PPU "
              "не согласованы в блоке 3.1 DendyConfig.h");
static_assert(DENDY_FRAME_US_DEN * 1000000ull * 1000ull
              == DENDY_FRAME_US_NUM * DENDY_FPS_MILLI,
              "период кадра (DENDY_FRAME_US_NUM/DEN) не равен 1/DENDY_FPS: "
              "проверьте дробь периода в блоке 3.1 DendyConfig.h");
static_assert(AUDIO_SAMPLE_RATE >= 8000 && AUDIO_SAMPLE_RATE <= 96000,
              "AUDIO_SAMPLE_RATE вне диапазона MAX98357 (8..96 кГц) — проверьте "
              "блок 3 «ЗВУК» DendyConfig.h");
static_assert(DENDY_CPU_HZ / AUDIO_SAMPLE_RATE >= 2,
              "окно сэмпла короче двух тактов CPU 2A03: антиалиасинг "
              "(DENDY_APU_ANTIALIAS) вырождается — проверьте AUDIO_SAMPLE_RATE "
              "и DENDY_CPU_HZ");
// Почему здесь больше НЕТ проверки «AUDIO_SAMPLE_RATE делится на частоту кадров»:
// сэмплы считает аккумулятор sampleAcc в NesApu::step() в тактах CPU, а не
// «735 сэмплов на кадр»: 22 050 даёт 367,5 — APU чередует 367/368 без дрейфа.
// Сэмплов APU на кадр — в среднем AUDIO_SAMPLE_RATE/FPS (735 при 44 100 и 60,
// 367,5 при 22 050). Из неё считается «подушка» звука игры: предзаполнение кольца
// тишиной перед стартом рома, чтобы задача I2S никогда не подходила к пустому
// кольцу (это и лечит хрип — см. подробный разбор в блоке 3 «ЗВУК»).
#define AUDIO_SAMPLES_PER_FRAME  (AUDIO_SAMPLE_RATE / (DENDY_FPS_MILLI / 1000))  // округлено
// «Подушка» считается без потери дробной части (22 050 даёт 367,5 сэмпла на кадр):
#define AUDIO_PRIME_SAMPLES      ((AUDIO_SAMPLE_RATE * AUDIO_PRIME_FRAMES \
                                   + (DENDY_FPS_MILLI / 1000) / 2) \
                                  / (DENDY_FPS_MILLI / 1000))
// Самопроверка: «подушка» вместе с одним блоком DMA обязана помещаться в кольцо с
// запасом — иначе предзаполнение само съест место для свежих сэмплов, и станет
// хуже, чем без него. AUDIO_RING_SIZE и AUDIO_DMA_FRAMES — в блоке 3 «ЗВУК».
static_assert(AUDIO_PRIME_SAMPLES + AUDIO_DMA_FRAMES <= AUDIO_RING_SIZE - 1,
              "«подушка» звука не помещается в кольцо APU: уменьшите "
              "AUDIO_PRIME_FRAMES (или AUDIO_RING_SIZE в NesApu::RING_SIZE)");
static_assert(AUDIO_DMA_FRAMES <= AUDIO_RING_SIZE - 1,
              "блок DMA больше кольца APU: задача I2S никогда не наберёт полный "
              "блок — проверьте AUDIO_DMA_FRAMES/AUDIO_RING_SIZE");
static_assert(AUDIO_FEED_IDLE <= AUDIO_DMA_FRAMES,
              "AUDIO_FEED_IDLE больше блока DMA: вставка тишины в пустое кольцо "
              "окажется длиннее обычного блока — проверьте блок 3 «ЗВУК»");
static_assert(AUDIO_START_GUARD_WAIT_MAX_MS <= 5000,
              "AUDIO_START_GUARD_MS + AUDIO_FIRST_SOUND_QUIET_MS больше 4500 мс: "
              "первый звук после включения будет ждать неприлично долго — "
              "проверьте блок 3 «ЗВУК» DendyConfig.h");
// Яркость при включении — в процентах от DISPLAY_BRIGHTNESS (блок 2 «ДИСПЛЕЙ»).
// 0 % и больше 100 % бессмысленны: первое гасит подсветку совсем (картинку не
// вернуть, пока не нажмёшь кнопку яркости), второе выходит за шкалу ШИМ.
static_assert(DISPLAY_BR_DEFAULT_PCT >= 1 && DISPLAY_BR_DEFAULT_PCT <= 100,
              "DISPLAY_BR_DEFAULT_PCT вне 1..100: проверьте блок 2 «ДИСПЛЕЙ» "
              "DendyConfig.h (это яркость при включении, в процентах)");
// Сколько кадров NES эмулятор может «догнать» за ОДИН проход игрового цикла.
// Значение 1 = «догонять нечего»: за проход эмулируется ровно один кадр, и он же
// уходит на экран. Это главный переключатель ПЛАВНОСТИ картинки.
// ЗАЧЕМ ИМЕННО 1: при 4 (как было) отставший эмулятор эмулировал пачку из
// нескольких кадров за проход, а на дисплей из пачки уходил только ПОСЛЕДНИЙ —
// то есть на экране оказывался 1 кадр из 3..4. В логе это выглядело так:
// `fps emu ~ 41, na ekran ~ 13` — игру «дёргало», как при 13 кадрах/с, хотя
// эмулировалось 41. Со значением 1 числа всегда совпадают: сколько кадров
// эмулировали — столько и показали (в логе `na ekran` == `fps emu`).
// ВАЖНО про скорость игры: она НЕ падает от того, что часть кадров не показана.
// Сколько кадров NES «наступает» за секунду, решает не дисплей, а сам эмулятор:
// пока он считает кадр быстрее 16,67 мс, игра идёт со 100 % скорости даже тогда,
// когда на экран уходит половина кадров. Но если эмулятор НЕ успевает
// (`emu` > 16,67 мс/кадр), отставание вернуть нечем: игра и музыка замедляются
// ровно на этот процент (см. про «песок» ниже).
// (Экран физически не ограничивает: передача кадра идёт на втором ядре, 15 мс на
// кадр, то есть до ~66 обновлений/с.)
#define DENDY_MAX_FRAME_SKIP   1      // 1 -> проход = 1 кадр = 1 обновление картинки
// --- ПОЧЕМУ ВЕРНУЛИСЬ НА 1 (было 2) ------------------------------------------
// Долг эмуляции по стен-часам ограничен величиной accMaxUs = период кадра × этот
// параметр (см. DendyGO.ino), а всё, что «не влезло», ЗАБЫВАЕТСЯ. При 2 долг до
// 33,3 мс не прощается: отставший эмулятор догоняет пропущенный кадр, эмулируя за
// проход ДВА кадра, а на экран из пачки уходит только ПОСЛЕДНИЙ.
// ЗАЧЕМ ОТКАЗАЛИСЬ ОТ 2: догон помогает только тогда, когда эмулятор УСПЕВАЕТ за
// 60 кадров/с. Если он медленнее (у нас `emu` ~20..23 мс на кадр вместо 16,67),
// долг не уменьшается НИКОГДА, и цикл постоянно эмулирует по 2 кадра за проход.
// Скорость игры от этого не растёт (кадров в секунду столько, сколько успевает
// CPU), а картинка обновляется вдвое реже: в логе `fps emu ~ 42` при `na ekran ~
// 23` — это и есть то «дёргается и тормозит», из-за чего значение вернули на 1.
// ЧТО ЭТО ДАЁТ: при 1 сколько кадров эмулировали — столько и показали (`na ekran`
// == `otdano` == `fps emu`), картинка ровная. На звук переход не влияет: APU
// отдаёт РОВНО AUDIO_SAMPLES_PER_FRAME сэмплов на каждый ЭМУЛИРОВАННЫЙ кадр (735
// при 60 Гц и 44 100), на медленном эмуляторе так же «худеет», и разницу теперь
// добирает растяжение (AUDIO_ADAPTIVE_RATE), а не вставка тишины («песок»).
// Самопроверка: предел накопленного долга за проход (accMaxUs в DendyGO.ino, он
// считается делением с округлением ВВЕРХ) обязан быть НЕ МЕНЬШЕ периода кадра —
// иначе цикл `while (frameAccUs >= nextFrameUs)` не увидит наступивший кадр и
// эмулятор встанет. Достаточно одной опечатки: при NTSC период равен 50 000/3 =
// 16 666,67 мкс, и округление вниз (16 666) уже меньше границы кадра (16 667).
// SKIP = 0 тоже отсекается: `emulated < 0` никогда не выполняется.
static_assert(((uint64_t)DENDY_FRAME_US_NUM * DENDY_MAX_FRAME_SKIP + DENDY_FRAME_US_DEN - 1)
              / DENDY_FRAME_US_DEN
              >= ((uint64_t)DENDY_FRAME_US_NUM + DENDY_FRAME_US_DEN - 1) / DENDY_FRAME_US_DEN,
              "DENDY_MAX_FRAME_SKIP мал: предел долга за проход получается меньше "
              "периода кадра — цикл эмуляции не увидит наступивший кадр и встанет "
              "(см. accMaxUs в DendyGO.ino)");
// Сколько кадров эмулировать за один проход игрового цикла (и, значит, как часто
// картинка обновляется на экране: кадр уходит на дисплей один раз за проход).
//   0 — (по умолчанию, когда DENDY_FRAME_DOUBLE_BUFFER = 1) «пачка» равна РОВНО
//       накопившемуся долгу по стен-часам: в норме ровно 1 кадр на проход, то
//       есть 60 проходов цикла и 60 обновлений картинки в секунду. Больше кадров
//       — только если эмулятор реально отстал (долг), не больше DENDY_MAX_FRAME_SKIP.
//       Передачу кадра цикл не ждёт (она идёт на втором ядре), поэтому длинные
//       пачки только вредят: ввод запаздывает на всю пачку, а картинка идёт
//       рывками. Именно этот режим и даёт «честные 60 кадров» по стен-часам.
//   1 — «пачка» дополнительно ограничивается временем передачи кадра: эмулируем
//       несколько кадров подряд только пока это дешевле самой передачи. Смысл
//       есть только при DENDY_FRAME_DOUBLE_BUFFER = 0, когда передача
//       синхронная (26..36 мс на кадр) и её надо «размазать» по кадрам.
#define DENDY_FRAME_BURST_BY_PUSH 0

// Перекрытие вывода кадра с эмуляцией (двойная буферизация + задача на втором ядре).
// ЗАЧЕМ: кадр 256x240 на 40 МГц SPI передаётся ~26 мс, и раньше это время
// эмулятор просто стоял (pushImage синхронный) — терялась половина времени CPU,
// и игра шла ровно вдвое медленнее приставки («1 секунда игры = 2 секунды
// реальности»). Теперь PPU рисует следующий кадр в ДРУГОЙ буфер (PSRAM, ещё
// 122 880 байт), а передачу ведёт отдельная задача на втором ядре:
// эмуляция и SPI работают параллельно, терять время на передачу больше не нужно.
//   1 — перекрывать (нужно ~240 КБ PSRAM: два кадра по 122 880 байт);
//   0 — как раньше: pushImage() синхронно, кадр уходит с полной остановкой CPU.
// Если PSRAM не хватит, режим сам отключится (в логе видно [VID] odin bufer).
#define DENDY_FRAME_DOUBLE_BUFFER 1
// Задача вывода кадра: ядро, приоритет, стек. Эмулятор работает на ядре 1
// (там же цикл Arduino; задача звука — на ядре 0, см. AUDIO_TASK_CORE), поэтому
// оба ядра заняты делом одновременно.
#define DENDY_PUSH_TASK_CORE   0
#define DENDY_PUSH_TASK_PRIO   3
#define DENDY_PUSH_TASK_STACK  4096
// Сколько максимум ждать передачи кадра (мкс): защита от вечного ожидания, если
// задача вывода почему-то встала. 200 мс — заведомо больше кадра (26 мс).
#define DENDY_PUSH_WAIT_US     200000UL

// --- ЭКСПЕРИМЕНТ «кто отбирает время у эмулятора» -----------------------------
// Сколько ЭМУЛИРОВАННЫХ кадров реально выводить на экран: 1 — все (как раньше),
// 2 — каждый второй, 3 — каждый третий. Игра при этом НЕ теряет кадры (PPU
// продолжает рисовать в тот же буфер, эмуляция и звук идут как шли) — просто
// картинка обновляется реже.
// ЗАЧЕМ: передача кадра 122 КБ по SPI и чтение буфера из PSRAM идут на другом
// ядре, но PSRAM и кэш у двух ядер ОБЩИЕ. Если «песок» в звуке/отставание игры
// от этого, то с 2 в строке [GAME] `emu ms/kadr` упадёт ниже 16,67 мс, а
// `fps emu` придёт к 60,0 (а после возврата на 1 — снова просядет). Это и есть
// ответ на вопрос «виноват эмулятор или вывод кадра»; чем уменьшать трафик — см.
// README, раздел «Картинка дороже звука». При 1 поведение ровно как было:
// сколько кадров посчитали — столько и показали (`na ekran` == `fps emu`).
#define DENDY_PUSH_EVERY_N_FRAMES 1

// Горячий код ядра (CPU/PPU/APU/маппер) в IRAM вместо flash-кэша.
// На ESP32-S3 код исполняется из flash через кэш 16 КБ: интерпретатор 6502
// (большой switch, объект NesCpu.cpp ~110 КБ) постоянно «промахивается» мимо
// кэша, и каждый промах — десятки тактов. IRAM читается за такт, поэтому
// эмуляция ускоряется (обычно в 1,3..2 раза).
// ЦЕНА (измерено на этой сборке): CPU ~28 КБ, PPU ~3,5 КБ, APU ~2,5 КБ, маппер
// ~0,8 КБ — всего ~35 КБ IRAM. В регионе IRAM этой прошивки свободно ~277 КБ
// (занято 74 КБ из 358 КБ), так что места с запасом. Если линковщик всё же
// напишет «region `iram0_0_seg' overflowed» — верните 0 (остальное работает).
// В логе сборки может появиться «warning: ignoring attribute 'section' …» —
// это нормально: и объявление, и определение помечены IRAM, gcc выбирает одну
// из секций; код всё равно оказывается в IRAM (видно по объектам).
#define DENDY_CORE_IRAM        1


// ============================ 4. КНОПКИ SX1509 ===============================
#define SX1509_ADDRESS         0x3E   // A0/A1 SX1509 на GND -> 0x3E
#define SX1509_I2C_FREQ        400000 // частота второй шины I2C (до 400 кГц)
#define SX1509_I2C_FREQ_SLOW   100000 // запасная частота: длинные проводки «звенят» на 400 кГц
#define SX1509_AUTO_SWAP_PINS  1      // 1 — если чип не отвечает, поменять SDA/SCL местами
#define SX1509_RESET_SETTLE_MS 5      // пауза после софт-ресета (SX1509 грузит настройки ~2 мс)
#define SX1509_BEGIN_TRIES     4      // попыток после begin() (библиотека читает тест без паузы)
#define SX1509_DEBOUNCE_MS     8      // аппаратный антидребезг SX1509 (0,1,2,4,8,16,32,64 мс)
#define TURBO_HALF_PERIOD_MS   33     // период "моргания" турбо-кнопки (33 мс -> ~15 Гц)
#define BTN_MENU_HOLD_MS       400    // удержание MENU -> выход в меню
// Минимальный интервал между ЧТЕНИЯМИ шины I2C в игре (мкс). Страховка от
// «шторма» обращений к SX1509: если провод INT не подключён и висит в воздухе
// (или залип в LOW), pollButtons() срабатывает на КАЖДОМ вызове, а вызывается он
// по разу на кадр — то есть до DENDY_MAX_FRAME_SKIP раз за проход игрового цикла.
// Каждое чтение — это 2 транзакции I2C (~0,2 мс на 400 кГц), и без ограничения
// кнопки отбирали бы у кадра миллисекунды (видно в строке [GAME] vremya -> `knopki`;
// там же поле `oprosov` — сколько раз реально читали шину за окно: ~60/с — норма,
// сотни — INT не работает/залип).
#define BTN_POLL_MIN_US        2000

// --- Раскладка кнопок на выводах SX1509 (0..15); активный уровень — LOW ---
// Список идёт ПО ФУНКЦИЯМ (как в прошивке), а номера выводов — по возрастанию
// в строке ниже, чтобы сразу видеть свободный вывод (15):
//   A=11 | B=12 | SELECT=13 | START=14 | Вверх=2 | Вниз=1 | Влево=3 | Вправо=0 |
//   TURBO A=9 | TURBO B=10 | MENU=7 | громкость «−»=5 | громкость «+»=6 |
//   REGION=4 | ЯРКОСТЬ=8   ==>  свободен: 15
// (Вывод 4 занят РЕГИОНом — см. SX_PIN_REGION ниже: в меню он переключает
//  TV: AUTO/NTSC/PAL.)
// Громкость выведена ДВУМЯ отдельными кнопками (SX_PIN_VOL_DOWN / SX_PIN_VOL_UP):
// они работают и в игре, и в меню, и не мешают SELECT+UP/DOWN (тот способ тоже
// остался). Удержание кнопки громкости повторяет шаг (AUDIO_VOLUME_REPEAT_MS).
//
// ВНИМАНИЕ: один вывод SX1509 не может обслуживать ДВЕ кнопки. Если переносите
// раскладку — сверьтесь со строкой выше: при опечатке одна кнопка «зажмёт» сразу
// два действия. От такой ошибки защищает static_assert в скетче (sxPinsUnique,
// сразу после таблицы SX_BTN_PAD).
#define SX_PIN_A               11     // A
#define SX_PIN_B               12     // B
#define SX_PIN_SELECT          13     // Select
#define SX_PIN_START           14     // Start
#define SX_PIN_UP              2      // Вверх
#define SX_PIN_DOWN            1      // Вниз
#define SX_PIN_LEFT            3      // Влево
#define SX_PIN_RIGHT           0      // Вправо
#define SX_PIN_TURBO_A         9      // Turbo A
#define SX_PIN_TURBO_B         10      // Turbo B
#define SX_PIN_MENU            7      // MENU (короткое — Reset, удержание — меню)
#define SX_PIN_VOL_DOWN        5      // громкость «−» (отдельная кнопка)
#define SX_PIN_VOL_UP          6      // громкость «+» (отдельная кнопка)
// РЕГИОН (PAL/NTSC): новое — выбор режима ТВ в меню, без пересборки прошивки.
// Короткое нажатие по кругу: AUTO -> NTSC -> PAL -> AUTO (текущий режим виден в
// меню справа вверху: «TV auto(NTSC)»). Кнопка нужна ТОЛЬКО в меню: регион
// применяется при запуске рома (см. applyRegionMode в скетче) — и «по горячему»
// переключать его в игре нельзя, потому что от него зависят и частота кадров, и
// число строк в кадре, и тактовая 2A03, то есть весь тайминг эмуляции.
// Вывод 4 у SX1509 был свободен (см. таблицу раскладки ниже).
#define SX_PIN_REGION          4      // REGION (в меню: AUTO/NTSC/PAL)
// ЯРКОСТЬ ЭКРАНА: короткое нажатие — следующая ступень по кругу (список
// DISPLAY_BR_STEPS_PCT в блоке 2 «ДИСПЛЕЙ»), при включении — DISPLAY_BR_DEFAULT_PCT.
// Работает и в игре, и в меню; выбранное значение нигде не сохраняется. Вывод 8 был
// свободен (см. таблицу раскладки выше).
#define SX_PIN_BRIGHT          8      // ЯРКОСТЬ (по кругу 5/15/25/50/75/100 %)

