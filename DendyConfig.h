// ПЕЧАТЬ ОБХОДИТСЯ ДОРОГО: 115200 бод — это ~11 КБ/с, длинная строка [SND]
// (~470 символов) занимает UART на ~40 мс, и пока буфер драйвера полон, задача
// эмулятора ЖДЁТ — это время прямо отбирается у кадра. Поэтому в игре теперь:
//   * [SND] — раз в 5 с (было раз в 1 с: одна только эта строка съедала ~4 %
//     канала UART и столько же времени у эмуляции);
//   * подробный блок [GAME] (sbor / подсказка / profil / kesh / vremya) — ОДИН РАЗ
//     за игру, и не в первом окне (первые 5 с — загрузка рома и прогрев кэшей);
//   * короткая строка [GAME] fps emu / na ekran / emu ms — раз в 5 с;
//   * в меню [SND] — раз в 2 с.
// Для «боевой» сборки (играем, а не измеряем) поставьте 0: это ещё ~2..4 % времени
// кадра, при этом дисплей и звук работают точно так же.
#define DENDY_SERIAL_BAUD      115200

// ==================== 0.1. ПОДРОБНАЯ ОТЛАДКА (Serial) =======================
// Работает только при DENDY_DEBUG_SERIAL = 1. Выключите (0), когда всё
// заработает: подробный лог остаётся удобным только для отладки.
//   DENDY_BTN_TRACE : скан шины I2C, дамп регистров SX1509, каждое нажатие
//                     кнопки (что прочитано и какая кнопка сработала).
//                     ВНИМАНИЕ: на КАЖДОЕ нажатие/отпускание печатается строка
//                     ~130 символов. На 115200 бод это ~11 мс занятого UART, и
//                     при полном буфере Serial.printf() ждёт (до 100 мс на USB
//                     CDC) — игра в этот момент «дёргается». Поэтому в 1 этот
//                     флаг держите только для разовой диагностики кнопок, а для
//                     игры держите 0 (в меню состояние кнопок и так видно).
//   DENDY_ROM_TRACE : листинг LittleFS (что реально лежит в файловой системе),
//                     раздел LittleFS (адрес/размер) и причина пропуска файлов.
//   DENDY_VIDEO_TRACE : видеотракт — сколько миллисекунд занимает эмуляция кадра
//                     и сколько его передача на экран, сколько пикселей в кадре
//                     отличаются от чёрного, регистры PPU и PC процессора.
//                     Тест-полосы по краям — отдельный флаг DENDY_VIDEO_TEST_STRIPS.
#define DENDY_BTN_TRACE        0
#define DENDY_ROM_TRACE        1
// ВНИМАНИЕ: видеотракт печатает ~35 строк лога на каждую секунду игры. На
// 115200 бод это заметная доля канала: UART тормозит игровой цикл, поэтому для
// НОРМАЛЬНОЙ игры оставляйте 0 (проверять видеотракт — отдельным запуском).
// ЗАМЕР НА ЭТОЙ ПЛАТЕ (почему по умолчанию 0 и почему это важно для ЗВУКА):
// с трассой, включённой во время игры, эмулятор Super Mario Bros шёл 44..53
// кадра/с вместо 60 — в логе `[VID] emu 22.8 ms, kadrov 44`, а в строке [SND]
// видно следствие: `kolco APU 0/2048`, растущие `tishina`/`dyra`, `nenulevyh`
// около 5 %. То есть кольцо APU пустело, и задача I2S добивала музыку тишиной
// (на слух это «песок»/хрип). Размеры буферов звука этого НЕ лечат: лечит только
// скорость эмуляции (60 кадров/с). Строку [SND] в игре теперь печатает и сборка
// с трассой 0 — см. пометку у logSoundDiag("игра") в скетче.
#define DENDY_VIDEO_TRACE      0
// СЕЙЧАС 0: с трассой эмулятор шёл 44..53 кадра/с, кольцо APU пустело и I2S
// добивал музыку тишиной — это и был «песок». Включать 1 только на отдельный
// запуск ради диагностики видеотракта (тогда о звуке судить нельзя).
// Цветные тест-полосы по краям экрана (четыре разных пути вывода кадра) и проба
// порядка каналов цвета справа. Очень помогают понять, «врёт» вывод или ядро, но
// во время игры их видно по бокам (игра занимает только 256 из 320 точек), и
// выглядят они как «цветные квадраты по краям + цифры 1..4 сверху справа».
// Включать только для диагностики, вместе с DENDY_VIDEO_TRACE.
#define DENDY_VIDEO_TEST_STRIPS 0
// Адреса ОЗУ эмулятора для дампа в лог (только при DENDY_VIDEO_TRACE = 1).
// Значения по умолчанию — для Super Mario Bros.: $0770 — режим игры (GameMode),
// $06FC — байт, который игра приняла из $4016 (биты: A,B,Select,Start,Up,Down,
